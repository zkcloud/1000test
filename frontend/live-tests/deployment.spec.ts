import { test, expect } from '@playwright/test'

test('公网 HTTPS、Secure Cookie、原版材料、练习解析与交卷', async ({ page, context }, info) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.locator('.exam-card')).toHaveCount(10)
  const cookie = (await context.cookies()).find(c => c.name === 'reader_visitor')
  expect(cookie?.secure).toBeTruthy(); expect(cookie?.httpOnly).toBeTruthy(); expect(cookie?.sameSite).toBe('Strict')
  await page.getByRole('button', { name: '进入练习', exact: true }).first().click()
  await page.getByLabel('练习范围').selectOption('6')
  await page.getByLabel('题组（可选）').selectOption({ label: 'Part 6 · Questions 131–134' })
  await page.getByRole('button', { name: '开始练习 →', exact: true }).click()
  await expect(page.getByLabel('选答后自动下一题')).not.toBeChecked()
  await expect(page.locator('.material-panel img').first()).toBeVisible()
  await expect.poll(() => page.locator('.material-panel img').first().evaluate((i: HTMLImageElement) => i.naturalWidth)).toBeGreaterThan(0)
  await page.locator('.option').nth(3).click()
  await expect(page.getByText('已保存到服务端', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '核对本题 · 答案与解析', exact: true }).click()
  await expect(page.getByRole('heading', { name: '正确答案 D', exact: true })).toBeVisible()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: `../reports/deployment/${info.project.name}-live-reading.png`, fullPage: true })
  await page.getByRole('button', { name: '结束练习', exact: true }).click()
  await page.getByRole('button', { name: '确认提交', exact: true }).click()
  await expect(page.locator('.score-card strong')).toHaveText('1/1')
  expect(errors).toEqual([])
})

test('公网考试交卷前不返回答案、NGINX 后评分及只读回顾', async ({ page }, info) => {
  await page.goto('/')
  await page.getByRole('button', { name: '开始考试', exact: true }).first().click()
  await page.getByRole('button', { name: '确认开始考试 →', exact: true }).click()
  await expect(page.locator('.options')).toBeVisible()
  const question = await page.evaluate(async () => { const id = location.hash.split('/')[2]; return (await fetch(`/api/attempts/${id}/questions/1`)).json() })
  expect(question).not.toHaveProperty('answer'); expect(question).not.toHaveProperty('explanation')
  await page.locator('.option').first().click()
  await expect(page.getByText('已保存到服务端', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '交卷', exact: true }).click()
  await page.getByRole('button', { name: '确认提交', exact: true }).click()
  await expect(page.locator('.score-card strong')).toHaveText('1/100')
  await page.screenshot({ path: `../reports/deployment/${info.project.name}-live-result.png`, fullPage: true })
  await page.getByRole('button', { name: '逐题回顾 →', exact: true }).click()
  await expect(page.getByRole('heading', { name: '正确答案 A', exact: true })).toBeVisible()
  await expect(page.locator('.option').first()).toBeDisabled()
})
